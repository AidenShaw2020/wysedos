"""Build ACPI 1.0 tables and standard SeaBIOS table-loader relocations.
Run: python tools/acpi/build.py path/to/iasl.exe
The generated header is checked in: normal monitor builds need no iASL.
"""
from pathlib import Path
import struct, subprocess, sys
root=Path(__file__).resolve().parent
subprocess.run([sys.argv[1],'-p',str(root/'dsdt'),str(root/'dsdt.asl')],check=True)
dsdt=(root/'dsdt.aml').read_bytes()
def header(sig,size,rev=1):
    return bytearray(struct.pack('<4sIBB6s8sI4sI',sig,size,rev,0,b'WYSEDS',b'WYSE3040',1,b'WYSE',1))
tables=bytearray(64) # FACS, aligned 64
tables[:8]=struct.pack('<4sI',b'FACS',64)
dsdt_off=len(tables);tables+=dsdt
while len(tables)%16:tables+=b'\0'
fadt_off=len(tables);fadt=header(b'FACP',116)+bytearray(80)
struct.pack_into('<II',fadt,36,0,dsdt_off) # FACS/DSDT: relative until BIOS relocates
struct.pack_into('<HI',fadt,46,9,0xB2)
fadt[52:54]=bytes((0xF1,0xF0))
struct.pack_into('<IIIIII',fadt,56,0x600,0,0x604,0,0,0x608)
fadt[88:92]=bytes((4,2,0,4))
struct.pack_into('<HH',fadt,96,0xffff,0xffff) # no C2/C3
struct.pack_into('<I',fadt,112,1) # WBINVD, fixed power button, 24-bit timer
tables+=fadt
rsdt_off=len(tables);tables+=header(b'RSDT',40)+struct.pack('<I',fadt_off)
rsdp=bytearray(struct.pack('<8sB6sBI',b'RSD PTR ',0,b'WYSEDS',0,rsdt_off))
name_t=b'etc/acpi/tables';name_r=b'etc/acpi/rsdp'
def cmd(n,p):return struct.pack('<I',n)+p.ljust(124,b'\0')
def name(n):return n.ljust(56,b'\0')
loader=bytearray()
for n,align,zone in [(name_t,64,1),(name_r,16,2)]:
    loader+=cmd(1,name(n)+struct.pack('<IB',align,zone))
for dst,src,off in [(name_r,name_t,16),(name_t,name_t,rsdt_off+36),
                     (name_t,name_t,fadt_off+36),(name_t,name_t,fadt_off+40)]:
    loader+=cmd(2,name(dst)+name(src)+struct.pack('<IB',off,4))
for n,off,start,size in [(name_r,8,0,20),(name_t,rsdt_off+9,rsdt_off,40),
                         (name_t,fadt_off+9,fadt_off,116)]:
    loader+=cmd(3,name(n)+struct.pack('<III',off,start,size))
out='/* Generated by tools/acpi/build.py. See dsdt.asl. */\n'
for n,b in [('acpi_tables',tables),('acpi_rsdp',rsdp),('acpi_loader',loader)]:
    out+=f'static const unsigned char {n}[] = {{\n'
    out+='\n'.join('    '+','.join(f'0x{x:02x}' for x in b[i:i+16])+',' for i in range(0,len(b),16))+'\n};\n'
(root/'../../pc/acpi_tables.h').resolve().write_text(out)
print('tables',len(tables),'loader',len(loader),'RSDT offset',rsdt_off)
