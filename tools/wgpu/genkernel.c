/* Prints the Gouraud pixel shader of gpu3d.c (four PLNs of attribute 0 into
 * g113-g120, a SIMD16 render-target write) as a C array, for the DOS test of
 * the render channel, which Open Watcom builds without gen8_asm.c. */
#include <stdio.h>
#include "gen8_asm.h"

#define RT_WRITE_SIMD16 0x10031000u   /* render target write, SIMD16, 8 registers, binding table 0 */

int main(void)
{
    Gen8Inst k[] = {
        gen8_pln(113, 6, 0), gen8_pln(115, 6, 16), gen8_pln(117, 7, 0), gen8_pln(119, 7, 16),
        gen8_send(5, 0, 113, RT_WRITE_SIMD16, 1),
    };
    unsigned n = sizeof k / sizeof k[0];
    printf("/* generated by tools/wgpu/genkernel.c from efi/platform/gen8_asm.c */\n");
    printf("static const uint32_t kernel_gouraud[%u] = {\n", n * 4);
    for (unsigned i = 0; i < n; i++)
        printf("    0x%08xu, 0x%08xu, 0x%08xu, 0x%08xu,\n", k[i].dw[0], k[i].dw[1], k[i].dw[2], k[i].dw[3]);
    printf("};\n");
    return 0;
}
